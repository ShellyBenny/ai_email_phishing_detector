"""
PDF Threat Report Generator for AI-Based Email Phishing Detection.
Exports a detailed, professional cybersecurity audit report using fpdf2.

Sections:
1. Executive Verdict & Risk Summary
2. Classification & Confidence Metrics
3. Explainability: Top Feature Attributions
4. Red Flag Findings (URLs, Urgency, Attachments, Headers)
5. Actionable Threat Mitigation Steps
"""

from datetime import datetime
from pathlib import Path
import sys
from fpdf import FPDF

CURRENT_DIR = Path(__file__).resolve().parent
BASE_DIR = CURRENT_DIR.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))


class ThreatReportPDF(FPDF):
    """Custom FPDF document layout."""

    def header(self):
        # Header banner
        self.set_fill_color(30, 41, 59)  # Dark slate
        self.rect(0, 0, 210, 20, "F")
        self.set_text_color(255, 255, 255)
        self.set_font("helvetica", "B", 12)
        self.set_xy(10, 5)
        self.cell(0, 10, "CYBERSECURITY INCIDENT & THREAT ANALYSIS REPORT", align="L")
        self.set_font("helvetica", "", 9)
        self.set_xy(140, 5)
        self.cell(60, 10, "AI Email Phishing Detector", align="R")
        self.ln(18)

    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(140, 140, 140)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}} - Confidentially Generated by AI Phishing Detection System", align="C")


def sanitize_text(text: str) -> str:
    """Sanitize strings to ensure ASCII/latin-1 compatibility in standard PDF fonts."""
    if not text:
        return ""
    # Replace common unicode quotes and symbols
    replacements = {
        "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
        "\u2013": "-", "\u2014": "--", "\u2026": "...", "\u2022": "*",
        "🚨": "[ALERT]", "⚠️": "[WARNING]", "✅": "[SAFE]", "•": "*"
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


def generate_pdf_report(scan_result: dict, email_raw_text: str = "") -> bytes:
    """
    Generate a complete PDF threat assessment report.

    Args:
        scan_result (dict): The output dictionary from PhishingPredictor.predict()
        email_raw_text (str): The raw scanned email text.

    Returns:
        bytes: Raw PDF document bytes ready for download or saving.
    """
    pdf = ThreatReportPDF(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    pred = scan_result.get("prediction", "Unknown")
    confidence = scan_result.get("confidence_score", 0.0)
    risk_score = scan_result.get("risk_score", 0.0)
    risk_level = scan_result.get("risk_level", "Medium")
    model_used = scan_result.get("model_used", "Best Model")
    probs = scan_result.get("probabilities", {})

    # 1. Executive Verdict Banner
    if pred == "Phishing":
        fill_rgb = (239, 68, 68)  # Red
        title_text = "VERDICT: PHISHING ATTACK DETECTED"
    elif pred == "Spam":
        fill_rgb = (245, 158, 11)  # Amber
        title_text = "VERDICT: UNSOLICITED SPAM / COMMERCIAL"
    else:
        fill_rgb = (34, 197, 94)  # Green
        title_text = "VERDICT: LEGITIMATE COMMUNICATION"

    pdf.set_fill_color(*fill_rgb)
    pdf.rect(10, 24, 190, 16, "F")
    pdf.set_xy(12, 26)
    pdf.set_font("helvetica", "B", 13)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(115, 12, title_text)

    pdf.set_xy(130, 26)
    pdf.set_font("helvetica", "B", 11)
    pdf.cell(65, 12, f"RISK: {risk_score}/100 [{risk_level.upper()}]", align="R")
    pdf.ln(18)

    # 2. Metadata Block
    pdf.set_text_color(51, 65, 85)
    pdf.set_font("helvetica", "B", 10)
    pdf.cell(95, 6, f"Scan Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S UTC')}")
    pdf.cell(95, 6, f"Classifier Model: {sanitize_text(model_used)}", align="R")
    pdf.ln(6)
    pdf.set_font("helvetica", "", 10)
    pdf.cell(95, 6, f"Confidence Score: {confidence:.2f}%")
    pdf.cell(95, 6, f"Assessed Risk Tier: {risk_level} Risk", align="R")
    pdf.ln(8)

    # 3. Class Probabilities Table
    pdf.set_font("helvetica", "B", 10)
    pdf.set_fill_color(241, 245, 249)
    pdf.cell(63, 7, "Legitimate Probability", border=1, align="C", fill=True)
    pdf.cell(64, 7, "Spam Probability", border=1, align="C", fill=True)
    pdf.cell(63, 7, "Phishing Probability", border=1, align="C", fill=True, new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("helvetica", "", 10)
    p_legit = probs.get("Legitimate", 0.0) * 100
    p_spam = probs.get("Spam", 0.0) * 100
    p_phish = probs.get("Phishing", 0.0) * 100
    pdf.cell(63, 7, f"{p_legit:.2f}%", border=1, align="C")
    pdf.cell(64, 7, f"{p_spam:.2f}%", border=1, align="C")
    pdf.cell(63, 7, f"{p_phish:.2f}%", border=1, align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # 4. Top Influential Words (Explainability)
    top_words = scan_result.get("top_words", [])
    if top_words:
        pdf.set_font("helvetica", "B", 11)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 7, "Top Influential Keywords (Mathematical Feature Attribution):")
        pdf.ln(7)
        pdf.set_font("helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)

        # 2-column key list
        col_w = 95
        for i in range(0, len(top_words), 2):
            w1 = top_words[i]
            t1 = f"* {sanitize_text(w1['word'])} (weight: +{w1['weight']:.4f})"
            if i + 1 < len(top_words):
                w2 = top_words[i + 1]
                t2 = f"* {sanitize_text(w2['word'])} (weight: +{w2['weight']:.4f})"
            else:
                t2 = ""
            pdf.cell(col_w, 6, t1)
            pdf.cell(col_w, 6, t2)
            pdf.ln(5)
        pdf.ln(3)

    # 5. Security Red Flags & Heuristics
    pdf.set_font("helvetica", "B", 11)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 7, "Security Red Flag Analysis & Triggered Heuristics:")
    pdf.ln(7)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)

    reasons = scan_result.get("risk_reasons", [])
    if reasons:
        for r in reasons[:8]:
            pdf.multi_cell(190, 5, f"- {sanitize_text(r)}")
            pdf.ln(1)
    else:
        pdf.cell(0, 6, "- No critical heuristics triggered.")
        pdf.ln(6)
    pdf.ln(3)

    # 6. Email Header Verification (if present)
    headers = scan_result.get("header_analysis", {})
    if headers.get("headers_present", False):
        pdf.set_font("helvetica", "B", 11)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 7, "Email Header (RFC 5322) & Authentication Verdicts:")
        pdf.ln(7)
        pdf.set_font("helvetica", "", 9)
        pdf.set_text_color(71, 85, 105)
        sender = headers.get("sender_info", {})
        pdf.cell(0, 5, f"Sender: {sanitize_text(sender.get('from_raw', ''))}")
        pdf.ln(5)
        if sender.get("reply_to_email"):
            pdf.cell(0, 5, f"Reply-To: {sanitize_text(sender.get('reply_to_email', ''))}")
            pdf.ln(5)
        auth = headers.get("auth_results", {})
        pdf.cell(0, 5, f"Authentication: SPF={auth.get('spf')} | DKIM={auth.get('dkim')} | DMARC={auth.get('dmarc')}")
        pdf.ln(7)

    # 7. Safety Recommendations
    tips = scan_result.get("safety_tips", {})
    steps = tips.get("steps", [])
    if steps:
        pdf.set_font("helvetica", "B", 11)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 7, "Incident Response & Safety Guidance:")
        pdf.ln(7)
        pdf.set_font("helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        for s in steps:
            pdf.multi_cell(190, 5, f"[>] {sanitize_text(s)}")
            pdf.ln(1)
        pdf.ln(4)

    # 8. Email Content Snippet
    if email_raw_text:
        pdf.set_font("helvetica", "B", 10)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 6, "Email Excerpt Scanned:")
        pdf.ln(6)
        pdf.set_font("courier", "", 8)
        pdf.set_fill_color(248, 250, 252)
        snippet = sanitize_text(email_raw_text[:500]) + ("..." if len(email_raw_text) > 500 else "")
        pdf.multi_cell(190, 4, snippet, border=1, fill=True)

    return bytes(pdf.output())


